function a = generator_voltage_setpoint()
%GENERATOR_VOLTAGE_SETPOINT  ASSUMPTION - G1 terminal voltage setpoint.
%
%   Question Q2 bundled two things: WHICH DISPATCH to solve, and WHAT TERMINAL
%   VOLTAGE to hold. The user answered Q2c, which settles the dispatch (compare
%   389.30 MW rated against 342.01 MW site-derated) but does not state a
%   setpoint. This file therefore records the setpoint as an assumption that is
%   DISCLOSED, not one that was approved, in the same way as
%   transformer_magnetising_inductance.m.
%
%   A PV bus needs a voltage as much as it needs a power. The choice cannot be
%   deferred, so it is made in the least committal way available and written
%   down here.
%
%   THIS FILE CONTAINS AN ASSUMPTION, NOT PLANT DATA.

a.Parameter        = 'G1 (SGen5-2000H) load-flow terminal voltage setpoint';
a.Value            = 1.00;
a.Unit             = 'pu of the 22 kV nameplate (= 22000 V)';

a.Reason           = [ ...
    'The generator is represented as a PV bus, which requires a voltage ', ...
    'magnitude as well as an active power. The AVR setpoint actually used at ', ...
    'the plant is not documented anywhere in the source set: there is no ', ...
    'operating instruction, no excitation record and no measured terminal ', ...
    'voltage. 1.00 pu of the machine''s own 22 kV nameplate is used, i.e. ', ...
    'the machine holds exactly its rated terminal voltage. This is the ', ...
    'single least-committal choice available - it is the nameplate value ', ...
    'rather than a number selected to improve any result, and it is the same ', ...
    'discipline as approved answer Q8a applies to transformer taps ', ...
    '(documented principal taps, not taps optimised to flatten the voltage ', ...
    'profile). A setpoint above 1.00 pu would raise the exported reactive ', ...
    'power and flatter the 230 kV voltage profile; that would be tuning the ', ...
    'answer, and it is not done.'];

a.Approved_by_user = false;
a.Date             = '2026-08-17';
a.Approved_answer  = [ ...
    'not applicable - implied by approved answer Q2c, which settles the ', ...
    'dispatch but not the setpoint. Disclosed, not approved.'];
a.Disclosure_note  = [ ...
    'Reported to the user with the Phase 7 delivery and shown on the model ', ...
    'title block ("|V| setpoint: ASSUMPTION"). If a documented AVR setpoint ', ...
    'is later found, this file and G(1).Vset_pu in ', ...
    'matlab/data/ashuganj_generators.m are the only places that change.'];

a.Impact           = [ ...
    'First-order on REACTIVE quantities, negligible on ACTIVE ones. The ', ...
    'setpoint fixes the 22 kV bus at exactly 1.000000 pu by construction, so ', ...
    'it propagates through the GSUT to set the 230 kV voltage and through the ', ...
    'UAT to set the 6.6 kV voltage. Active power is unaffected: P is ', ...
    'dispatched, and the losses that depend on voltage are second order. The ', ...
    'reported generator Q, the reactive export at the plant boundary and the ', ...
    'MV bus voltage all move with this number, and none of them should be ', ...
    'quoted without it.'];

a.Impact_quantified = [ ...
    'Not swept, and that is a deliberate limitation to state rather than ', ...
    'hide. A setpoint sweep would be a reactive-dispatch study, not a ', ...
    'balanced load flow of the documented network, and it would answer a ', ...
    'question the source set cannot pose. What IS quantified is the ', ...
    'consequence of the setpoint being held: matlab/tests/test_grid_sensitivity.m ', ...
    'measures that the 22 kV bus stays at 1.000000 pu across an 8x range of ', ...
    'grid impedance (to 1e-6 pu), which is exactly what a PV constraint at ', ...
    'this setpoint means, and it shows the reactive consequence - Qgen moves ', ...
    'from +29.06 to +43.20 MVAr across that range while the setpoint holds.'];

a.Source           = [ ...
    'The 22 kV nameplate voltage IS documented (Siemens SGen5-2000H rating ', ...
    'plate, VERIFIED_PLANT). What is assumed is only that the machine is ', ...
    'held AT that voltage rather than above or below it.'];

a.Affects          = {'G1', 'B22', 'and through the transformers every other bus voltage'};
a.Status_assigned  = 'ENGINEERING_ASSUMPTION';
end
