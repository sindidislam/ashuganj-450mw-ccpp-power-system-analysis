function a = aux_load_allocation_split()
%AUX_LOAD_ALLOCATION_SPLIT  APPROVED ASSUMPTION - auxiliary load distribution.
%
%   Approved by the user on 2026-08-17 in answer to question Q6, option (B).
%   User's stated reason: "Better than putting everything at one bus. The
%   9050:2500:2500 split is based on actual documented motor ratings,
%   although the allocation must be labelled an assumption."
%
%   The user's own qualifier - "the allocation must be labelled an
%   assumption" - is the reason this file exists.
%
%   THIS FILE CONTAINS AN ASSUMPTION, NOT PLANT DATA.

a.Parameter        = 'Allocation of the 14 MW documented auxiliary load across three 6.6 kV nodes';
a.Value            = [9050, 2500, 2500];
a.Unit             = 'kW (ratio only - see Derived_MW below for the applied result)';

a.Nodes            = {'B6_6', 'B6_6_WI1', 'B6_6_WI2'};
a.Derived_MW       = 14.0*[9050, 2500, 2500]/14050;
a.Derived_MVAr     = 14.0*tan(acos(0.85))*[9050, 2500, 2500]/14050;

a.Reason           = [ ...
    'Two separate facts have to be distinguished here. (1) The 14 MW total ', ...
    'auxiliary load at 0.85 power factor is documented project data - it is ', ...
    'VERIFIED and is not part of this assumption. (2) The ratio ', ...
    '9050:2500:2500 comes from documented MOTOR RATINGS (installed kW) of ', ...
    'the main auxiliary group and the two water-intake / large-motor ', ...
    'groups - also documented. What is NOT documented, and what this file ', ...
    'covers, is the step of apportioning the 14 MW OPERATING total across ', ...
    'that INSTALLED-RATING ratio. No per-node metered demand exists in the ', ...
    'source set. Installed rating is not demand: motors run at part load, ', ...
    'and different groups have different duty cycles and diversity ', ...
    'factors, none of which are documented. The apportionment is therefore ', ...
    'an assumption, and it is labelled one.'];

a.Approved_by_user = true;
a.Date             = '2026-08-17';
a.Approved_answer  = 'Q6 option (B) - distributed load';

a.Impact           = [ ...
    'Smaller than it looks, and this must be stated honestly in the report. ', ...
    'The 6.6 kV FEEDER CABLE IMPEDANCES ARE MISSING (see ', ...
    'matlab/data/ashuganj_lines.m), so the three load nodes are connected ', ...
    'to the MV bus with ZERO impedance. Consequently: (1) all three nodes ', ...
    'solve to exactly the same voltage; (2) the total P and Q drawn through ', ...
    'the UAT are IDENTICAL to the single-lumped-bus case; (3) the ', ...
    'transformer loading, the generator output and every bus voltage in the ', ...
    'model are therefore UNCHANGED by this assumption. What the split ', ...
    'genuinely buys is a load model whose structure matches the documented ', ...
    'plant, which is what the later protection-coordination phase needs ', ...
    'when feeder impedances become available. What it does NOT buy is ', ...
    'feeder voltage drop, and the report must not imply that it does.'];

a.Impact_quantified = [ ...
    'Exactly zero effect on all solved quantities relative to a single 14 MW ', ...
    'load at B6_6, because the interconnecting impedance is zero. This is ', ...
    'asserted and CHECKED numerically by matlab/tests/test_load_data.m, ', ...
    'which re-solves with the lumped load and compares every bus voltage.'];

a.Source           = [ ...
    'Ratio: documented motor ratings, project data set. ', ...
    'Total: documented 14 MW / 0.85 pf, project data set. ', ...
    'The APPORTIONMENT of the total across the ratio: no source - this is ', ...
    'the assumed step.'];

a.Warning          = [ ...
    'The 14 MW total is numerically equal to the UAT no-load loss expressed ', ...
    'in kW (14 kW) and to 3.60 percent of the 389.30 MW rated output. Both ', ...
    'are coincidences, were checked during the audit, and are NOT evidence ', ...
    'of a transcription error.'];

a.Affects          = {'LOAD_B6_6', 'LOAD_B6_6_WI1', 'LOAD_B6_6_WI2'};
a.Status_assigned  = 'ENGINEERING_ASSUMPTION';
end
