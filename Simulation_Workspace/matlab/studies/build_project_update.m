navs = { '1. Where the project stands', 's1'
         '2. What the model represents', 's2'
         '3. How to run it', 's3'
         '4. The Simulink model, block by block', 's4'
         '5. The MATLAB code, file by file', 's5'
         '6. Key code, and what each piece does', 's6'
         '7. Load flow results', 's7'
         '8. What the results mean', 's8'
         '9. Assumptions and missing data', 's9'
         '10. What remains', 's10'
         '11. Complete file map', 's11' };
for k = 1:size(navs,1)
    w('<li><a href="#%s">%s</a></li>\n', navs{k,2}, navs{k,1});
end
w('</ol></nav>\n');

% ================================================================== 1 status
w('<section id="s1"><h2>1. Where the project stands</h2>\n');
w('<p>The plant''s electrical single-line diagram has been rebuilt as a working Simulink model and a balanced load flow has been solved on it. Four operating cases converge and cross-check. Nothing about faults or protection has been attempted yet &mdash; that is the next stage, and this stage is its input.</p>\n');
