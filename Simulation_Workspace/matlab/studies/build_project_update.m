% =====================================================================
function snip(fid, root, rel, anchor, nlines, why)
%SNIP  Quote a real excerpt from a source file, with its line numbers.
%
%   Anchored on a LINE OF CODE, never on a line number, so ordinary edits above
%   the excerpt cannot silently shift the quote onto the wrong lines. If the
%   anchor is gone, the page says so and quotes nothing: a confidently wrong
%   excerpt is worse than a missing one, and the same rule applies to code as to
%   parameter values.
f = fullfile(root, 'matlab', rel);
fprintf(fid, '<div class="snip"><div class="sh"><code>%s</code><span>%s</span></div>\n', ...
    rel, why);
if ~exist(f, 'file')
    fprintf(fid, ['<p class="warn"><code>%s</code> is not on disk, so nothing ' ...
        'was quoted from it.</p></div>\n'], rel);
    return
end
L = readlines(f);
i = find(startsWith(strtrim(L), anchor), 1);
if isempty(i)
    fprintf(fid, ['<p class="warn">The anchor line is no longer present in ' ...
        '<code>%s</code>, so no excerpt was quoted rather than the wrong lines ' ...
        'being quoted. Re-point the anchor in ' ...
        '<code>build_project_update.m</code>.</p></div>\n'], rel);
    return
end
j = min(i + nlines - 1, numel(L));
seg = L(i:j);

% Dedent by the smallest indent present, so an excerpt taken from inside a loop
% does not arrive with a stray four spaces on every line.
pad = inf;
for k = 1:numel(seg)
    s = char(seg(k));
    if isempty(strtrim(s)), continue, end
    pad = min(pad, numel(s) - strlength(strip(string(s), 'left')));
end
if ~isfinite(pad), pad = 0; end

txt = '';
for k = 1:numel(seg)
    s = char(seg(k));
    if numel(s) > pad, s = s(pad+1:end); else, s = strtrim(s); end
    txt = [txt esc(s) newline];                                   %#ok<AGROW>
end
fprintf(fid, '<pre class="code">%s</pre>\n', txt);
fprintf(fid, '<div class="sl">%s, lines %d&ndash;%d</div></div>\n', rel, i, j);
end

