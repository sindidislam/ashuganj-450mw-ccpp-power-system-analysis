w('</div>\n');
w(['<p class="note"><b>Stage plan.</b> (1) <b>Load flow &mdash; done, this document.</b> ' ...
   '(2) Short-circuit study: three-phase, single-line-to-ground, line-to-line, ' ...
   'double-line-to-ground. (3) Protection coordination and relay settings. ' ...
   'Stages 2 and 3 need data the load flow does not &mdash; listed in &sect;9.</p>\n']);
w('</section>\n');

