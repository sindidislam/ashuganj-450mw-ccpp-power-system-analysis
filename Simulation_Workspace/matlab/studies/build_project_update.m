% =====================================================================
function s = nd(v, fmt)
%ND  Format a number, or an em dash if the solver could not attribute one.
%   A merged bus has no injection of its own - not an unknown value, a question
%   with no answer in that network. It is shown as a dash, never as 0.
if isnan(v), s = '&mdash;'; else, s = sprintf(fmt, v); end
end

% =====================================================================
function s = esc(s)
%ESC  HTML-escape source text. Ampersand first, or the escapes escape each other.
s = strrep(s, '&', '&amp;');
s = strrep(s, '<', '&lt;');
s = strrep(s, '>', '&gt;');
end

