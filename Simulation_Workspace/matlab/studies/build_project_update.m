function build_project_update(varargin)
%BUILD_PROJECT_UPDATE  Write docs/manual/PROJECT_UPDATE.html - the presentation.
%
%   BUILD_PROJECT_UPDATE                 write the HTML
%   BUILD_PROJECT_UPDATE('Solve', false) use the CSVs already in results/
%
%   WHAT THIS IS FOR
%   ----------------
%   One self-contained HTML file to present the project as it stands: what the
%   model is, how to run it, what every MATLAB file and every Simulink block
%   does, what the load flow found, and what is still open. It is a project
%   UPDATE, not a lab report - the audience is the group and the course teacher,
%   and the question it answers is "where are we and what is left".
%
%   WHY IT IS GENERATED AND NOT HAND-WRITTEN
%   ----------------------------------------
%   Every number in it is read from results/load_flow/*.csv, which is written by
%   run_load_flow_study. A hand-written page would start drifting from the
%   dataset the first time a parameter changed. Nothing here is retyped.
%
%   The one thing this file may NOT do is invent a number. If a CSV is missing a
%   column the page says so; it does not fill the gap.

p = inputParser;
p.addParameter('Solve', false, @islogical);
p.parse(varargin{:});
opt = p.Results;

root = ashuganj_root();
lfDir = fullfile(root, 'results', 'load_flow');
outDir = fullfile(root, 'docs', 'manual');
if ~exist(outDir, 'dir'), mkdir(outDir); end

if opt.Solve
    run_load_flow_study();
end

sumFile = fullfile(lfDir, 'system_summary.csv');
if ~exist(sumFile, 'file')
    error('build_project_update:noResults', ...
        ['results/load_flow/system_summary.csv does not exist. Run ' ...
         'run_load_flow_study first, or call this with (''Solve'', true).']);
end
SUM = readtable(sumFile);
TX  = readtable(fullfile(lfDir, 'transformer_results.csv'));
BUS = readtable(fullfile(lfDir, 'bus_results.csv'));
GEN = readtable(fullfile(lfDir, 'generator_results.csv'));
D   = ashuganj_master_data();

% ---- figures are COPIED beside the HTML, not linked across the tree --------
% docs/manual/ then survives being zipped, emailed or opened on another PC with
% no MATLAB and no project folder. A figure that has not been generated yet is
% reported as absent on the page; it is never faked or silently omitted.
srcFigs = { fullfile(root,'results','diagrams','Load_Flow_LF1_Annotated.png')
            fullfile(root,'results','diagrams','Load_Flow_LF2_Annotated.png')
            fullfile(root,'results','plots','power_balance.png')
            fullfile(root,'results','plots','bus_voltage_profile.png')
            fullfile(root,'results','plots','transformer_loading.png')
            fullfile(root,'results','plots','line_loading.png') };
for k = 1:numel(srcFigs)
    if exist(srcFigs{k}, 'file')
        [~, nm, ex] = fileparts(srcFigs{k});
        copyfile(srcFigs{k}, fullfile(outDir, [nm ex]));
    end
end

out = fullfile(outDir, 'PROJECT_UPDATE.html');
fid = fopen(out, 'w');
if fid < 0, error('build_project_update:open', 'Cannot write %s', out); end
c = onCleanup(@() fclose(fid));

w = @(varargin) fprintf(fid, varargin{:});

% ===================================================================== head
w('<!DOCTYPE html>\n<html lang="en"><head>\n');
w('<meta charset="utf-8">\n');
w('<meta name="viewport" content="width=device-width, initial-scale=1">\n');
w('<title>Ashuganj South - Load Flow Model - Project Update</title>\n');
w('<style>\n%s</style>\n', css());
w('</head>\n<body>\n');

% ===================================================================== title
w('<header>\n');
w('<div class="course">EEE 306 &middot; Power System I Laboratory &middot; January 2026 &middot; Group-03, Section C-1</div>\n');
w('<h1>Protection Coordination and Fault Analysis of the<br>Ashuganj 450 MW Combined Cycle Power Plant (South)</h1>\n');
w('<div class="sub">Project update &mdash; <b>Stage 1 of 3: balanced steady-state load flow</b></div>\n');
w('<div class="meta">Model: MATLAB R2024a &middot; Simulink 24.1 &middot; Simscape Electrical (Specialized Power Systems) &middot; 50 Hz &middot; %g MVA base</div>\n', ...
  D.base.Sbase_MVA);
