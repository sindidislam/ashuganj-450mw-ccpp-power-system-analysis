w('<h3>Assumptions are kept somewhere else on purpose</h3>\n');
afiles = dir(fullfile(root, 'matlab', 'data', 'assumptions', '*.m'));
w(['<p>There are <b>%d</b> of them, in <code>matlab/data/assumptions/</code>, ' ...
