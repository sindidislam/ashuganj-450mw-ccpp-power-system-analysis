end
w('</tbody></table>\n');
w(['<p>Every value in those files carries where it came from: the document, the ' ...
   'page or sheet, and a status &mdash; verified from the plant, verified from ' ...
   'an engineering document, derived, assumed, estimated, missing or ' ...
   'conflicting. Keep that column truthful when you add anything. A number ' ...
   'without a source is worse than a gap, because a gap gets filled and a wrong ' ...
