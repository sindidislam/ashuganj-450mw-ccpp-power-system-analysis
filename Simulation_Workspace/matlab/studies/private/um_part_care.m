% =====================================================================
function s = first_help_line(f)
%FIRST_HELP_LINE  The one-line summary from a function's own help text.
%   Read from the file, so a file that is renamed or rewritten cannot end up
%   described here by a stale sentence.
s = '<i>no summary line in the file</i>';
L = readlines(f);
[~, base] = fileparts(f);
for i = 1:min(8, numel(L))
    t = strtrim(char(L(i)));
    if ~startsWith(t, '%'), continue, end
    t = strtrim(t(2:end));
    if isempty(t), continue, end
    [tok, rest] = strtok(t);
    if strcmpi(tok, base), t = strtrim(rest); end
    if ~isempty(t), s = um_esc(t); return, end
end
end

% =====================================================================
function f = pipeline_files(root)
%PIPELINE_FILES  Every MATLAB file a run actually executes.
%   The entry point, the dataset, the builders, the analysis, the studies and
%   the tests. These are the files that have to be portable.
f = dir(fullfile(root, '*.m'));
sub = { 'ashuganj.m', 'ashuganj_setup.m' };
for k = 1:numel(sub)
    f = [f; dir(fullfile(root, 'matlab', sub{k}))];                   %#ok<AGROW>
end
sub = { 'data', 'utilities', 'build', 'analysis', 'studies', 'tests' };
for k = 1:numel(sub)
    f = [f; dir(fullfile(root, 'matlab', sub{k}, '**', '*.m'))];      %#ok<AGROW>
end
end

% =====================================================================
function f = scratch_files(root)
%SCRATCH_FILES  The one-off probes kept as a record of what was measured.
%   Not on the MATLAB path, not called by anything, and not executed by a run.
%   matlab/gui/ is deliberately NOT included: the interactive interface there is
%   live work, not a scratch script, and it is not this study's to report on.
f = dir(fullfile(root, 'matlab', 'env', '*.m'));
end

% =====================================================================
function [nAbs, nScan, hits] = absolute_path_scan(f)
%ABSOLUTE_PATH_SCAN  Count files holding an absolute path on an executable line.
%   Comment lines are skipped: several legitimately quote where MATLAB itself is
%   installed, which is documentation and not a dependency. Only a drive letter
%   on a line that runs makes a file unportable.
%
%   The pattern requires the drive letter to open a quoted string - 'F:\...' or
%   "C:/..." - which is how a hard-coded path is actually written. Matching a
%   bare letter-colon-separator instead flags every format string that ends
%   ':\n', and a check that cries wolf gets ignored, which is worse than not
%   having one.
pat = '[''"][A-Za-z]:[\\/]';
nAbs = 0; nScan = numel(f); hits = {};
for k = 1:numel(f)
    L = readlines(fullfile(f(k).folder, f(k).name));
    bad = false;
    for i = 1:numel(L)
        t = strtrim(char(L(i)));
        if isempty(t) || startsWith(t, '%'), continue, end
        if ~isempty(regexp(t, pat, 'once')), bad = true; break, end
    end
    if bad
        nAbs = nAbs + 1;
        hits{end+1} = ['<code>' f(k).name '</code>'];                 %#ok<AGROW>
    end
end
end
