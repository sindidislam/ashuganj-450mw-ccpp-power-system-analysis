function G = ashuganj_grid()
%ASHUGANJ_GRID  External grid equivalent - Ashuganj 450 MW CCPP SOUTH.
%
%   G = ASHUGANJ_GRID() returns the Thevenin equivalent of the PGCB 230 kV
%   network at the plant boundary.
%
%   ============ READ THIS BEFORE USING ANY NUMBER BELOW ============
%   NO VERIFIED PGCB GRID STRENGTH EXISTS IN THE SOURCE SET.
%
%   The 50 kA figure is the ESTIMATED Siemens external-grid source quantity
%   from Generator Data-South §2.4 High voltage network (GRID): UNgrid 230 kV;
%   XN 2,66 estimated [= 2.66, European decimal comma]; Sk 19.919 [= 19,919 MVA,
%   European decimal]; Ik 50 kA. Line 95 prints XN = UNgrid/(3*IK'') with the
%   root symbol lost in extraction; executed math uses √3 giving |Z| =
%   2.65581124 ohm. XN ≈ 2.66 is the separately-reported rounded estimate;
%   |Z| = 2.65581124 is DERIVED via V^2/Ssc — never pair them as an exact R/X.
%   Equipment ratings are documented independently as EQUIPMENT RATINGS
%   (GIS 50 kA / 1 s + 3 s short-time withstand, 125 kA peak withstand,
%   50 kA making) and are NOT the source of this estimate.
%
%   Approved answer Q1a: use the impedance implied by that source quantity ONLY
%   as an explicitly labelled ESTIMATE, never as verified data.  Every result
%   that depends on it must say so.  Its status is therefore ESTIMATED, and it
%   is the single weakest number in the whole model.
%   =================================================================
%
%   Phase 3 (Task 4): the equivalent sits at B230_REMOTE behind the locked
%   0.7 km physical line L_LINE (B230_1 -> B230_REMOTE). Numerical estimate
%   unchanged (ESTIMATED). Q7a history: no 70 km line; pre-Phase-3 the
%   equivalent sat at the plant boundary B230_1.
%
%   See also ASHUGANJ_LINES, ASHUGANJ_MASTER_DATA.

G.Name              = 'EXT_GRID';
G.Label             = 'EXT GRID';
G.Bus_internal      = 'BGRID230';
G.Bus_boundary      = 'B230_1';
G.Bus_remote        = 'B230_REMOTE';   % display only: ZGRID spans BGRID230->B230_REMOTE since Phase-3 Task 4; solver wiring uses port handles, not this string
G.Grid_equivalent_bus = 'B230_REMOTE'; % display/semantic field (REV3.1 reconciliation): grid-equivalent connection bus; solver uses port handles; Bus_boundary kept for legacy fallback
G.Operator          = 'PGCB 230 kV network';

% ---- Voltage -----------------------------------------------------------
G.Vnom_V            = 230000;
G.Vnom_Status       = 'VERIFIED_ENGINEERING_DOCUMENT';
G.Vnom_Source       = 'SLD Rev 03 - 230 kV switchyard nominal voltage';

G.Vset_pu           = 1.00;
G.Vset_V            = G.Vset_pu*G.Vnom_V;
G.Vset_Status       = 'ENGINEERING_ASSUMPTION';
G.Vset_Note         = ['The actual PGCB busbar voltage at Ashuganj is NOT ', ...
                       'documented. 1.00 pu is used. This is a slack-bus ', ...
                       'setpoint, deliberately un-tuned: it is NOT adjusted ', ...
                       'to make plant voltages look good, consistent with ', ...
                       'approved answer Q8a on tap positions. Every solved ', ...
                       'voltage in the model scales essentially linearly ', ...
                       'with this figure, so the reader can rescale.'];
G.PhaseAngle_deg    = 0;
G.PhaseAngle_Status = 'DERIVED_FROM_VERIFIED_DATA';
G.PhaseAngle_Note   = 'Angle reference of the whole study, by definition of the slack bus.';

G.f_Hz              = 50;
G.f_Status          = 'VERIFIED_PLANT';
G.f_Note            = ['50 Hz. The prior CYME PSAF studies in the source set ', ...
                       'were built at 60 Hz (defect D2); that frequency is ', ...
                       'rejected outright, not averaged or reconciled.'];

% ---- Short-circuit level: the ESTIMATE and its provenance -------------
G.Isc_kA            = 50;
G.Isc_Status        = 'ESTIMATED';
G.Isc_Source        = ['Siemens Generator Data-South §2.4 High voltage network (GRID): ', ...
                       'UNgrid 230 kV; XN 2,66 estimated [=2.66]; Sk 19.919 [=19,919 MVA]; ', ...
                       'Ik 50 kA. ESTIMATED Siemens external-grid source quantity. ', ...
                       'Equipment 50 kA/1 s+3 s, 125 kA peak, 50 kA making are ', ...
                       'separate EQUIPMENT RATINGS, not this source.'];
G.Isc_Warning       = ['Treating the §2.4 estimated source quantity as a firm fault level ', ...
                       'assumes the network is exactly as strong as the Siemens estimate. ', ...
                       'That is a source estimate, so this model figure is an ESTIMATE ', ...
                       'on grid strength and therefore a LOWER BOUND on ', ...
                       'grid impedance. Consequence: the model understates ', ...
                       'the boundary voltage deviation caused by plant ', ...
                       'export. Direction of the error is known; magnitude ', ...
                       'is not.'];

G.Ssc_MVA           = sqrt(3)*G.Vnom_V*G.Isc_kA*1000/1e6;
G.Ssc_Status        = 'DERIVED_FROM_VERIFIED_DATA';   % derived FROM AN ESTIMATE
G.Ssc_Derivation    = 'S = sqrt(3) * 230 kV * 50 kA';
G.Ssc_Note          = ['DERIVED_FROM_VERIFIED_DATA describes the ARITHMETIC ', ...
                       'only. The INPUT is ESTIMATED, so the result inherits ', ...
                       'ESTIMATED confidence. Do not quote this as verified.'];

% ---- Equivalent impedance ---------------------------------------------
G.XR_ratio          = inf;
G.XR_Status         = 'ENGINEERING_ASSUMPTION';
G.XR_Note           = ['Q1a approved: X/R is NOT documented, so no ', ...
                       'resistance is invented. R = 0 exactly, giving an ', ...
                       'infinite X/R. MEASURED effect (test_grid_sensitivity ', ...
                       'Part 2, which corrected an earlier wrong claim here ', ...
                       'that the angle shift is "slightly overstated"): the ', ...
                       'boundary ANGLE is essentially INVARIANT under X/R ', ...
                       '(0.0072 deg spread), because holding |Z| fixed pins ', ...
                       'X to within 2 %. What DOES move is the boundary ', ...
                       'voltage MAGNITUDE, and upward - R = 0 OVERSTATES the ', ...
                       'sag, so the model is pessimistic there - together ', ...
                       'with grid losses (zero here, 0.704 MW at X/R = 10) ', ...
                       'and generator MVAr (-16.8 % at X/R = 10). The cause ', ...
                       'is that this plant exports P and Q in a ratio near ', ...
                       '12.6 to 1, so R*P dominates X*Q and the usual ', ...
                       'mostly-reactive transmission intuition inverts. ', ...
                       'See matlab/data/assumptions/grid_series_resistance_zero.m'];

G.R_ohm             = 0;
G.R_Status          = 'ENGINEERING_ASSUMPTION';

G.Z_ohm             = G.Vnom_V^2/(G.Ssc_MVA*1e6);
G.X_ohm             = sqrt(G.Z_ohm^2 - G.R_ohm^2);    % = Z_ohm since R = 0
G.X_Status          = 'ESTIMATED';
G.X_Source          = ['|Z| = V^2/S_sc = 2.65581124 ohm DERIVED from the §2.4 50 kA ', ...
                       'ESTIMATED Siemens source quantity. XN ≈ 2.66 is the ', ...
                       'separately-reported rounded estimate in §2.4, not an R/X pair. ', ...
                       'ESTIMATE, per approved answer Q1a.'];
G.L_H               = G.X_ohm/(2*pi*G.f_Hz);
G.L_Status          = 'DERIVED_FROM_VERIFIED_DATA';
G.L_Derivation      = 'L = X / (2*pi*50)';

% ---- Load-flow representation -----------------------------------------
G.LF_BusType        = 'swing';
G.Model_block       = 'sps_lib/Sources/Three-Phase Source';
G.Model_treatment   = 'ideal source + explicit external series branch';
G.Model_Note        = ['The source itself is IDEAL (NonIdealSource = off) ', ...
                       'and the equivalent impedance is a SEPARATE ', ...
                       'Three-Phase Series RLC Branch between BGRID230 and ', ...
                       'B230_REMOTE (Phase-3; plant bus B230_1 connects via ', ...
                       'the L_LINE PI section). This is deliberate and it matters: SPS ', ...
                       'enforces the swing voltage at the source TERMINAL, ', ...
                       'so an impedance placed INSIDE the source block ', ...
                       'would be bypassed by the load-flow voltage ', ...
                       'constraint and the grid would behave as infinitely ', ...
                       'stiff at B230_REMOTE. Putting it outside makes the ', ...
                       'boundary voltage genuinely respond to plant export.'];
G.InternalConnection = 'Yg';
G.InternalConnection_Status = 'ENGINEERING_ASSUMPTION';
G.InternalConnection_Note   = ['The PGCB 230 kV network is effectively ', ...
                       'solidly earthed, but no earthing document is in the ', ...
                       'set. Yg is used. NO effect on a balanced load flow.'];

G.Qmin_MVAr         = -inf;
G.Qmax_MVAr         =  inf;
G.Qlim_Status       = 'NOT_APPLICABLE';
G.Qlim_Note         = 'A slack bus absorbs whatever the network requires, by definition.';

% ---- Expected effect, stated in advance so the result can be checked --
G.Expected_effect   = ['At full rated export (about 375 MW leaving the GSUT ', ...
                       'HV terminal) the boundary current is roughly 0.94 ', ...
                       'kA and the angle shift across the grid equivalent ', ...
                       'is about atan(P*X/V^2) = atan(375e6*2.656/230e3^2) ', ...
                       'which is near 1.1 deg, with only a small change in ', ...
                       'voltage magnitude. If the solved result departs far ', ...
                       'from this, the model is wrong, not the plant.'];

% ------------------------------------------------------------------------
% Integrity assertions
% ------------------------------------------------------------------------
assert(G.Vnom_V == 230000, 'ashuganj_grid: grid must be at 230 kV. No 400 kV in South scope.');
assert(G.f_Hz == 50, 'ashuganj_grid: grid must be 50 Hz, not the 60 Hz of the prior PSAF studies.');
assert(G.R_ohm == 0, 'ashuganj_grid: R must be 0 per approved answer Q1a.');
assert(G.X_ohm > 0 && G.X_ohm < 100, 'ashuganj_grid: grid X is out of any plausible range.');
assert(strcmp(G.Isc_Status,'ESTIMATED'), ...
    ['ashuganj_grid: the grid short-circuit figure must remain ESTIMATED. ', ...
     'It is the §2.4 Siemens estimated source quantity, not verified PGCB data.']);
assert(strcmp(G.X_Status,'ESTIMATED'), ...
    'ashuganj_grid: grid X must remain ESTIMATED.');
end
