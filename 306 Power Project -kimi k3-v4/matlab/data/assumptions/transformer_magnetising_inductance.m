function a = transformer_magnetising_inductance()
%TRANSFORMER_MAGNETISING_INDUCTANCE  SUPERSEDED - Lm is now DERIVED, not assumed.
%
%   ==================================================================
%   THIS ASSUMPTION HAS BEEN RETIRED. ITS STATED REASON WAS FALSE.
%   ==================================================================
%
%   It claimed that no-load CURRENT was "absent from every rating plate and
%   every engineering document in the set" and that "there is therefore no
%   derivation path". That was true of the rating PLATES and false of the
%   DATA SHEETS, which had not yet been read when this file was written:
%
%     GSUT Data Sheet_South.pdf (S009-112070-00-ELC-HD-0001 Rev 00,
%       Siemens Transformer Guangzhou, 24.02.14), "Excitation current -
%       at 100 % of the rated voltage" ....................... 0.13 %
%     UAT  Data Sheet_South.pdf (S009-112070-00-ELC-HD-1001 Rev 00,
%       Siemens Wuhan, 27.03.14), section 1.1 p.5, UAT ....... ~0.3 %
%       and section 2.1 p.16, GAT ............................. 0.3 %
%
%   A derivation path existed the whole time. Lm is therefore now DERIVED in
%   matlab/data/ashuganj_transformers.m as
%
%       Lm(pu) = 1 / sqrt(I0^2 - (1/Rm)^2)
%
%   subtracting in quadrature the loss component that Rm already carries, so
%   the total excitation current is not double-counted:
%
%              Rm (pu)    I0 (%)    Lm (pu)    Qm at 1.0 pu V
%     GSUT      3239.0      0.13      791.9      0.650 MVAr
%     UAT       1785.7      0.3       339.3      0.074 MVAr
%     GAT       1087.0      0.3       350.2      0.071 MVAr
%                                                ----------
%                                                0.795 MVAr
%
%   WHY THIS FILE STILL EXISTS
%   --------------------------
%   Because deleting it would erase the error. The project's own precedent is
%   matlab/env/probe_loadflow_bus3.m, which carries the banner "ITS CONCLUSION
%   WAS WRONG" and is kept for exactly this reason, and
%   docs/validation/solver_behaviour.md B11, which closes "a validation record
%   that only lists successes is not a validation record". The same standard
%   applies to an assumption register: one that quietly drops its own retired
%   entries is not an audit trail.
%
%   It is registered under D.superseded, NOT D.assumptions. It enters nothing
%   into the model. ashuganj_master_data() asserts it cannot appear in both.
%
%   HOW BADLY IT ERRED
%   ------------------
%   In the SAFE direction, but loosely. It bounded the omitted reactive
%   absorption by re-solving at Lm = 100 pu, a 1 % magnetising current - 7.7x
%   the GSUT's documented 0.13 % - and published +3.4406 MVAr of generator Q
%   as the worst case. The as-built derived figure is measured against that
%   same bound by matlab/tests/test_magnetising_sensitivity.m, which now keeps
%   Lm = 1e6 as its first probe precisely so the cost of this error is a
%   measurement rather than a claim.
%
%   THIS FILE IS A HISTORICAL RECORD. IT IS NEITHER PLANT DATA NOR A LIVE
%   ASSUMPTION, AND NO PARAMETER IN THE MODEL COMES FROM IT.

a.Parameter        = 'Magnetising inductance Lm of GSUT, UAT and GAT';
a.Value            = 1e6;
a.Unit             = 'pu (i.e. numerically open circuit) - NO LONGER IN USE';

a.Reason_as_written = [ ...
    'PRESERVED VERBATIM AS THE RECORD OF THE ERROR - do not act on it. ', ...
    '"The magnetising branch has two elements and the source set supports ', ...
    'exactly one of them. NO-LOAD LOSS is documented for all three ', ...
    'transformers (GSUT 159 kW, UAT 14 kW, GAT 23 kW), so the magnetising ', ...
    'RESISTANCE is legitimately DERIVED as Rm(pu) = S_rated / P_no-load, ', ...
    'giving 3239.0, 1785.7 and 1087.0 pu respectively - those are derived ', ...
    'from verified data and are NOT part of this assumption. NO-LOAD ', ...
    'CURRENT, however, is absent from every rating plate and every ', ...
    'engineering document in the set, and it is the only quantity from ', ...
    'which Lm could be obtained. There is therefore no derivation path. ', ...
    'The block cannot be left blank, so Lm = 1e6 pu is entered, which is ', ...
    'numerically an open circuit and represents the honest position: the ', ...
    'model claims no magnetising reactive absorption because none is ', ...
    'documented."'];

a.Why_it_was_wrong = [ ...
    'The sentence "absent from every rating plate AND every engineering ', ...
    'document in the set" overreached. The first half was correct: neither ', ...
    'nameplate photograph shows an excitation current. The second half was ', ...
    'not checked, because at the time of writing the GSUT and UAT/GAT data ', ...
    'sheets had not been read - only the nameplates and the SLDs had. Both ', ...
    'data sheets publish the excitation current explicitly, as a labelled ', ...
    'row at 100 %, 105 % and 110 % of rated voltage. The failure was not a ', ...
    'wrong judgement about a genuinely missing number; it was declaring a ', ...
    'number MISSING before the document set had been exhausted. That is the ', ...
    'transferable lesson: MISSING is a claim about the whole source set and ', ...
    'may only be asserted once the whole source set has actually been read.'];

a.Superseded_by    = [ ...
    'matlab/data/ashuganj_transformers.m - Lm_pu is computed as ', ...
    '1/sqrt(I0^2 - (1/Rm)^2) from the documented excitation currents and ', ...
    'carries Lm_Status = DERIVED_FROM_VERIFIED_DATA. The I_noload_pct ', ...
    'fields, previously NaN/MISSING, now hold 0.13, 0.3 and 0.3 with ', ...
    'I_noload_Status = VERIFIED_ENGINEERING_DOCUMENT and the page cited.'];

a.Superseded_date  = '2026-08-19';
a.Superseded_values = struct( ...
    'GSUT', struct('I0_pct', 0.13, 'Rm_pu', 3239.0, 'Lm_pu', 791.9, 'Qm_MVAr', 0.650), ...
    'UAT',  struct('I0_pct', 0.30, 'Rm_pu', 1785.7, 'Lm_pu', 339.3, 'Qm_MVAr', 0.074), ...
    'GAT',  struct('I0_pct', 0.30, 'Rm_pu', 1087.0, 'Lm_pu', 350.2, 'Qm_MVAr', 0.071));

a.Approved_by_user = false;
a.Date             = '2026-08-17';
a.Approved_answer  = 'not applicable - was disclosed but never approved, and is now retired by data rather than by decision';
a.Disclosure_note  = [ ...
    'Was reported to the user as part of the Phase 7 delivery, flagged as ', ...
    'one of the two assumptions NOT approved. The user never had to rule on ', ...
    'it: the source documents settled it instead. No user decision is ', ...
    'pending on this entry - it is closed.'];

a.Impact_when_live = [ ...
    'Understated transformer no-load reactive absorption by the full 0.795 ', ...
    'MVAr of magnetising draw now represented. NO effect on active-power ', ...
    'flow, on transformer loading in MW, or on the active power balance, ', ...
    'because Rm - the element that carries iron loss - was always derived ', ...
    'from the documented no-load losses and was never part of this ', ...
    'assumption. The error was confined to reactive power and to the small ', ...
    'voltage drop the extra magnetising current causes.'];

a.Impact_quantified = [ ...
    'matlab/tests/test_magnetising_sensitivity.m now solves the base case at ', ...
    'Lm = 1e6 (this retired treatment), at the derived values, and at 500, ', ...
    '200 and 100 pu probes, and reports the generator Q shift, the B230_1 ', ...
    'and B6_6 voltage shifts and the real-loss shift for each. The ', ...
    'open-circuit-to-derived delta is the measured cost of this error.'];

a.Source           = [ ...
    'None - this file records the deliberate absence of a value that turned ', ...
    'out not to be absent. The data that superseded it: GSUT Data Sheet_South.pdf ', ...
    'excitation-current row, and UAT  Data Sheet_South.pdf sections 1.1 (p.5) ', ...
    'and 2.1 (p.16). Note the caveats carried forward with those figures - ', ...
    'the UAT value is printed "~0.3" (approximate in the source) and the ', ...
    'GSUT row carries the sheet''s own footnote that it "might be subject ', ...
    'due change after finalizing the transformer''s detailed design". Those ', ...
    'caveats are why the sensitivity sweep is retained rather than dropped.'];

a.Affects          = {'GSUT', 'UAT', 'GAT'};
a.Status_assigned  = 'SUPERSEDED';
end
