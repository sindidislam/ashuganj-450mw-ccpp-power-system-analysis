function a = gis_bus_coupler_closed()
%GIS_BUS_COUPLER_CLOSED  APPROVED ASSUMPTION - 230 kV GIS bus coupler state.
%
%   Approved by the user on 2026-08-17 in answer to question Q9, option (a).
%   User's stated reason: "Reasonable base case, but clearly label it as an
%   assumption because the normal state wasn't found in the available
%   document set."
%
%   The user's own qualifier - "clearly label it as an assumption because the
%   normal state wasn't found" - is why this file exists.
%
%   THIS FILE CONTAINS AN ASSUMPTION, NOT PLANT DATA.

a.Parameter        = '230 kV GIS bus coupler (BUS 1 - BUS 2) normal operating state';
a.Value            = 'closed';
a.Unit             = 'switch state (boolean)';

a.Reason           = [ ...
    'The Siemens 8DN9 230 kV GIS is a double-busbar single-breaker ', ...
    'arrangement. The BUSBARS, the bay layout and the disconnector scheme ', ...
    'are all fully documented (each bay has Q0 circuit-breaker, Q1 to ', ...
    'BUS 2, Q2 to BUS 1, Q9 earthing switch). What is NOT documented ', ...
    'anywhere in the available set is the NORMAL OPERATING STATE of the bus ', ...
    'coupler - no operating diagram, no normal-switching document and no ', ...
    'commissioning state record was found. A double busbar can legitimately ', ...
    'be run either coupled (single electrical node, common fault level) or ', ...
    'split (two independent nodes, halved fault level, load transferred ', ...
    'between sections). Both are normal engineering practice and the ', ...
    'documents do not say which one Ashuganj South uses. Coupled is chosen ', ...
    'as the base case because it is the more usual arrangement for a single ', ...
    'generating block with few bays, and because it is the case in which the ', ...
    'GAT loop is actually closed and therefore the case that exercises the ', ...
    'network topology most fully.'];

a.Approved_by_user = true;
a.Date             = '2026-08-17';
a.Approved_answer  = 'Q9 option (a) - coupler closed';

a.Impact           = [ ...
    'Material only in the GAT-in-service cases. With the coupler CLOSED, ', ...
    'B230_1 and B230_2 are one electrical node, so the GAT (on BUS 2) and ', ...
    'the GSUT (on BUS 1) see the same 230 kV voltage and the loop ', ...
    'GSUT -> 22 kV -> UAT -> 6.6 kV -> GAT -> 230 kV is CLOSED. That loop is ', ...
    'the whole consequence of this assumption, and it does NOT do what an ', ...
    'earlier version of this record predicted. It predicted that the ', ...
    'auxiliary load would divide between the UAT and the GAT according to ', ...
    'their impedances. THE MEASURED RESULT IS DIFFERENT AND MORE ', ...
    'CONSEQUENTIAL: the load does not divide at all. Closing the coupler ', ...
    'creates a second parallel path between the 22 kV bus and the 230 kV bus, ', ...
    'and because the two paths have very different impedances their voltage ', ...
    'angles differ, so a CIRCULATING EXPORT FLOW appears. In LF2 the 6.6 kV ', ...
    'bus settles 1.72 deg AHEAD of the 230 kV bus, and roughly 5.9 MW of the ', ...
    'plant''s export detours 22 kV -> UAT -> 6.6 kV -> GAT -> 230 kV instead ', ...
    'of going through the GSUT. The GAT therefore EXPORTS from the auxiliary ', ...
    'bus rather than helping to feed it, and the UAT carries the 14 MW ', ...
    'auxiliary load PLUS that circulating 5.9 MW. Consequence: UAT loading ', ...
    'rises from 90.64 % to 109.50 % of its 19 MVA ONAN rating (LF1 -> LF2) ', ...
    'and from 90.65 % to 101.39 % (LF3 -> LF4). Both looped cases exceed ', ...
    'the UAT''s natural-cooling rating, and the excess is circulating power, ', ...
    'not load. Total plant export is essentially unchanged (374.484 -> ', ...
    '374.467 MW); only the routing and the losses change. With the coupler ', ...
    'OPEN and the GAT in service, the GAT would be fed only through whatever ', ...
    'else connects to BUS 2, which the documents do not establish, and the ', ...
    'case would become indeterminate. In the GAT-out-of-service cases (LF1 ', ...
    'and LF3) the coupler state has NO effect at all, because BUS 2 then ', ...
    'carries nothing.'];
a.Impact_quantified = [ ...
    'Quantified directly by the case matrix: compare LF1 vs LF2 (rated ', ...
    'dispatch) and LF3 vs LF4 (derated dispatch). The difference between ', ...
    'each pair IS the effect of closing the loop through the coupler. ', ...
    'Measured in results/load_flow/transformer_results.csv: ', ...
    'UAT S_HV 17.2222 -> 20.8054 MVA (90.64 -> 109.50 % of the 19 MVA ONAN ', ...
    'stage, 68.89 -> 83.22 % of the 25 MVA ONAF stage) and GAT S_HV ', ...
    '0.0035 -> 7.7128 MVA between LF1 and LF2; UAT S_HV 17.2226 -> 19.2640 ', ...
    'MVA (90.65 -> 101.39 %) between LF3 and LF4. The circulating power is ', ...
    'visible as opposing signs on P_LV: the UAT''s -19.9047 MW (into the ', ...
    '6.6 kV bus) against the GAT''s +5.9051 MW (out of it), whose difference ', ...
    'is the 14.000 MW auxiliary load to within the KCL residual. Confirmed ', ...
    'independently on the GSUT, whose HV throughput falls 374.486 -> ', ...
    '368.596 MW - a 5.890 MW reduction matching the 5.871 MW that arrives at ', ...
    'the 230 kV busbar through the GAT instead. Plant loss rises 0.81612 -> ', ...
    '0.83326 MW, i.e. the detour costs about 17 kW.'];

a.Operational_caveat = [ ...
    'A finding for the report rather than a modelling problem. Simultaneously ', ...
    'closing the UAT and the GAT onto one 6.6 kV bus, with the two ', ...
    'transformers fed from different sources, is normally an INTERLOCKED ', ...
    'TRANSFER condition - momentary, during changeover - rather than a steady ', ...
    'operating state, precisely because it parallels two sources through the ', ...
    'auxiliary system. The measured UAT overload above its ONAN rating is ', ...
    'consistent with that reading. The source set contains no interlock ', ...
    'schedule, so LF2 and LF4 are solved and reported as specified by ', ...
    'approved answer Q4c, and this caveat is recorded rather than used as ', ...
    'grounds to drop the cases. If an interlock schedule is later found and ', ...
    'it forbids the parallel, LF2 and LF4 become transfer-transient cases ', ...
    'rather than steady-state ones and should be described as such.'];

a.Source           = [ ...
    'None for the state itself. The GIS arrangement, bay numbering ', ...
    '(10BAY11 / 10BAY12 coupler / 10BAY20 GAT), 3150 A bus-coupler/busbar module rating ', ...
    'and 50 kA / 1 s+3 s, 125 kA peak equipment ratings ARE documented in the ', ...
    'Siemens GIS data sheet and SLD Rev 03; only the normal coupler position is absent. ', ...
    'Bay modules are 2000 A (transformer/line); 3150 A is the bus-coupler/busbar module only.'];

a.Related          = [ ...
    'Approved answer Q10a depends on this one: the choice of which busbar ', ...
    'each bay is selected to (BUS 1 or BUS 2) does not materially affect ', ...
    'the balanced network PRECISELY BECAUSE the coupler is assumed closed. ', ...
    'If this assumption were reversed, the bay selection would become a ', ...
    'first-order modelling decision rather than a cosmetic one.'];

a.Affects          = {'B230_1', 'B230_2', 'BUS_COUPLER breaker', 'GAT loop closure'};
a.Status_assigned  = 'ENGINEERING_ASSUMPTION';
end
