def build(root=ROOT):
    if root.resolve() != ROOT.resolve():
        raise ValueError("This builder is scoped to the explicit v4 workspace.")
    baseline = HERE / "baseline_sha256.json"
    entries = json.loads(baseline.read_text(encoding="utf-8"))
    verification = check_preservation(root, entries)
    if verification["changed"] or verification["missing"]:
        raise RuntimeError(f"Original evidence changed: {verification}")
    output = root / "results/presentation"
    output.mkdir(parents=True, exist_ok=True)
    from fault_protection import build_fault_protection
    from dynamic_results import build_dynamic_results
    data = build_fault_protection(root, output)
    data["phase6"] = build_dynamic_results(root, output)
    data["emergency"] = emergency_section(root, output)
    data = clean_json(data)
    verification = check_preservation(root, entries)
    if verification["changed"] or verification["missing"]:
        raise RuntimeError(f"An adapter altered original evidence: {verification}")
    (output / "preservation_check.json").write_text(json.dumps(verification, indent=2), encoding="utf-8")
    (output / "report_data.json").write_text(json.dumps(data, ensure_ascii=False, indent=2, allow_nan=False), encoding="utf-8")
    (output / "index.html").write_text(render(data, verification), encoding="utf-8")
    for path, target in [(root/"START_RESULTS.html", "results/presentation/index.html"),
                         (root/"results/index.html", "presentation/index.html")]:
        if path.exists() and "ADDITIVE_RESULTS_READER" not in path.read_text(encoding="utf-8"):
            raise RuntimeError(f"Refusing to overwrite existing file: {path}")
        path.write_text(f'<!doctype html><!-- ADDITIVE_RESULTS_READER --><meta charset="utf-8"><title>V4 Results</title><meta http-equiv="refresh" content="0;url={target}"><a href="{target}">Open the v4 results reader</a>', encoding="utf-8")
    manifest = {"generated": datetime.now().astimezone().isoformat(timespec="seconds"),
                "root": root.name, "originals": verification, "sections": {
                    key: {"tables": len(section.get("tables", [])), "rows": count_rows(section),
                          "figures": len(section.get("figures", []))} for key,section in data.items()},
                "html_sha256": sha256(output/"index.html")}
    (output / "build_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(json.dumps(manifest, indent=2))
    return output / "index.html"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
