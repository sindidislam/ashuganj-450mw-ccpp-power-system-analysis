def sha256(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def check_preservation(root, entries):
    changed, missing = [], []
    for entry in entries:
        path = root / entry["path"]
        if not path.is_file():
            missing.append(entry["path"])
        elif sha256(path) != entry["sha256"]:
            changed.append(entry["path"])
    return {"checked": len(entries), "changed": changed, "missing": missing}


def clean_json(value):
    if isinstance(value, dict):
        return {str(k): clean_json(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [clean_json(v) for v in value]
    if isinstance(value, float) and not math.isfinite(value):
        return None
    if isinstance(value, Path):
        return value.as_posix()
    if hasattr(value, "item"):
        return clean_json(value.item())
    return value


def json_for_html(value):
    return json.dumps(clean_json(value), ensure_ascii=False, allow_nan=False).replace("<", "\\u003c")


def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        return list(reader.fieldnames or []), list(reader)


def numerical(value):
    try:
        x = float(value)
        return x if math.isfinite(x) else None
    except (ValueError, TypeError):
        return value


def emergency_section(root, output):
    source = root / "results/emergency_supply"
    if not (source / "summary.csv").exists():
        raise FileNotFoundError("Run RUN_EMERGENCY_SUPPLY first; emergency results/summary.csv is missing.")
    destination = output / "emergency"
    destination.mkdir(parents=True, exist_ok=True)
    descriptions = {
        "summary": "Emergency supply — operating conditions",
        "bus_results": "Bus voltages with the generator disconnected",
        "supply_paths": "Which source supplies each auxiliary service",
        "assumptions": "Source data, assumptions and missing plant information",
        "dc_summary": "Station DC continuity and autonomy",
        "dc_timeseries": "Station DC measured or calculated time record",
        "edg_screening": "Emergency diesel capacity screening",
        "validation": "Emergency calculation checks",
        "baseline_comparison": "Existing normal baseline versus emergency supply",
        "branch_results": "Transformer loading and branch flow",
    }
    tables = []
    for path in sorted(source.glob("*.csv")):
        columns, rows = read_csv(path)
        shutil.copy2(path, destination / path.name)
        tables.append({"title": descriptions.get(path.stem, path.stem.replace("_", " ").title()),
                       "columns": columns, "rows": [{k: numerical(v) for k, v in row.items()} for row in rows],
                       "csv": f"emergency/{path.name}"})
    order = ["summary", "baseline_comparison", "bus_results", "branch_results", "supply_paths",
             "dc_summary", "edg_screening", "validation", "assumptions", "dc_timeseries"]
    tables.sort(key=lambda t: order.index(Path(t["csv"]).stem) if Path(t["csv"]).stem in order else 99)
    figures = []
    for path in sorted(source.rglob("*.png")):
        shutil.copy2(path, destination / path.name)
        figures.append({"title": path.stem.replace("_", " ").title(), "path": f"emergency/{path.name}",
                        "caption": "Generated by the additive emergency study. Assumptions and operating-condition definitions are recorded in the tables below."})
    from emergency_figures import build_emergency_figures
    figures.extend(build_emergency_figures(root, output))
    notes = [
        "This added emergency study preserves the existing case definitions, model files and saved results. A disconnected generator supplies neither active nor reactive power.",
        "Grid supply requires an intact modeled backfeed path and the stated switching condition. A solved power-flow point does not validate the actual station transfer logic or motor restart sequence.",
        "Station DC supports only the explicitly represented controls, protection and emergency DC loads. It does not supply the 14 MW AC auxiliary load.",
        "No installed diesel rating, essential AC load schedule, UPS rating, transfer delay or battery capacity is inferred from absent plant data. Academic values, where used, remain labeled in the assumption register.",
    ]
    return {"title": "Emergency auxiliary supply", "label": "Added case · generator disconnected",
            "intro": "Follow the auxiliary supply after loss of the main generator: grid backfeed where available, station DC continuity, and the requirements for emergency diesel or UPS support.",
            "tables": tables, "figures": figures, "notes": notes}


def count_rows(section):
    return sum(len(t.get("rows", [])) for t in section.get("tables", []))


